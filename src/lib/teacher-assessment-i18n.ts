const dictionaries: Record<Locale, Dict> = { az, tr, en, ru };
const localeTags: Record<Locale, string> = { az: "az-AZ", tr: "tr-TR", en: "en-US", ru: "ru-RU" };

function interpolate(template: string, vars?: Vars) {
  if (!vars) return template;
  return Object.entries(vars).reduce((result, [key, value]) => result.replaceAll(`{${key}}`, String(value)), template);
}

export function useTeacherAssessmentI18n() {
  const { locale } = useI18n();
  const t = useCallback((key: TeacherAssessmentKey, vars?: Vars) => interpolate(dictionaries[locale][key] ?? az[key], vars), [locale]);
  const formatDateTime = useCallback((value: string | null | undefined) => {
    if (!value) return t("noDate");
    const date = new Date(value);
    if (!Number.isFinite(date.getTime())) return t("noDate");
    return new Intl.DateTimeFormat(localeTags[locale], {
      timeZone: "Asia/Baku",
      year: "numeric",
      month: "short",
      day: "2-digit",
      hour: "2-digit",
      minute: "2-digit",
    }).format(date);
  }, [locale, t]);

  return { locale, t, formatDateTime };
}
