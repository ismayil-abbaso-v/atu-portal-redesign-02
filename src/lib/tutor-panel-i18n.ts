const dictionaries: Record<Locale, Dict> = { az, en, tr, ru };

function interpolate(value: string, vars?: Vars) {
  if (!vars) return value;
  return value.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

export function tutorPanelTranslate(locale: Locale, key: TutorPanelKey, vars?: Vars) {
  return interpolate(dictionaries[locale][key] ?? az[key], vars);
}

export function useTutorPanelI18n() {
  const { locale, intlLocale } = useI18n();
  const t = useCallback((key: TutorPanelKey, vars?: Vars) => tutorPanelTranslate(locale, key, vars), [locale]);
  return { locale, intlLocale, t };
}

